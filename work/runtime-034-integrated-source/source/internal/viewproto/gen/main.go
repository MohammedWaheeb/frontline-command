// Command gen writes explicit converters for the public view only. Reflection
// is a build-time check of the JSON contract, never part of the snapshot path.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"reflect"
	"sort"
	"strings"

	"frontlinecommand/pkg/sim"
	pb "frontlinecommand/protocol"
)

type conversion struct{ from, to reflect.Type }

var pending = map[string]conversion{}

func name(t reflect.Type) string { return "to" + t.Name() }
func typename(t reflect.Type) string {
	if t.Kind() == reflect.Pointer {
		return "*" + typename(t.Elem())
	}
	if t.Kind() == reflect.Slice {
		return "[]" + typename(t.Elem())
	}
	if t.PkgPath() == "frontlinecommand/pkg/sim" {
		return "sim." + t.Name()
	}
	if t.PkgPath() == "frontlinecommand/protocol" {
		return "pb." + t.Name()
	}
	return t.String()
}
func convert(expr string, from, to reflect.Type) string {
	if from.Kind() == reflect.Pointer {
		if to.Kind() != reflect.Pointer {
			panic("pointer presence lost: " + expr)
		}
		return fmt.Sprintf("optional(%s, func(v %s) %s { return %s })", expr, typename(from.Elem()), typename(to), convert("v", from.Elem(), to))
	}
	if to.Kind() == reflect.Pointer {
		if from.Kind() == reflect.Struct {
			key := to.Elem().Name()
			pair := conversion{from, to.Elem()}
			if prior, ok := pending[key]; ok && prior != pair {
				panic("ambiguous conversion " + key)
			}
			pending[key] = pair
			return name(to.Elem()) + "(" + expr + ")"
		}
		return "pointer(" + convert(expr, from, to.Elem()) + ")"
	}
	if from.Kind() == reflect.Slice {
		if to.Kind() != reflect.Slice {
			panic("slice mismatch: " + expr)
		}
		return fmt.Sprintf("list(%s, func(v %s) %s { return %s })", expr, typename(from.Elem()), typename(to.Elem()), convert("v", from.Elem(), to.Elem()))
	}
	if from.Kind() == reflect.String && to.Kind() == reflect.String {
		return "text(" + expr + ")"
	}
	if from == to {
		return expr
	}
	if from.ConvertibleTo(to) {
		return typename(to) + "(" + expr + ")"
	}
	panic("unsupported conversion: " + expr + " " + from.String() + " -> " + to.String())
}
func function(c conversion) string {
	fromFields := map[string]reflect.StructField{}
	for i := 0; i < c.from.NumField(); i++ {
		f := c.from.Field(i)
		j := strings.Split(f.Tag.Get("json"), ",")[0]
		if j != "-" && j != "" {
			fromFields[j] = f
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "func %s(v %s) *%s { return &%s{\n", name(c.to), typename(c.from), typename(c.to), typename(c.to))
	for i := 0; i < c.to.NumField(); i++ {
		f := c.to.Field(i)
		if f.Tag.Get("protobuf") == "" {
			continue
		}
		j := strings.Split(f.Tag.Get("json"), ",")[0]
		source, ok := fromFields[j]
		if !ok {
			panic(c.to.Name() + " missing source for " + j)
		}
		if strings.Contains(source.Tag.Get("json"), ",omitempty") && source.Type.Kind() != reflect.Pointer && source.Type.Kind() != reflect.Struct && source.Type.Kind() != reflect.Slice && f.Type.Kind() == reflect.Pointer {
			panic("optional scalar omission needs an explicit converter: " + source.Name)
		}
		fmt.Fprintf(&b, "%s: %s,\n", f.Name, convert("v."+source.Name, source.Type, f.Type))
		delete(fromFields, j)
	}
	if len(fromFields) != 0 {
		panic(fmt.Sprintf("unmapped public fields %s: %v", c.from.Name(), fromFields))
	}
	b.WriteString("} }\n")
	return b.String()
}
func main() {
	pending["PlayerSnapshot"] = conversion{reflect.TypeOf(sim.View{}), reflect.TypeOf(pb.PlayerSnapshot{})}
	complete := map[string]string{}
	for len(complete) < len(pending) {
		keys := []string{}
		for key := range pending {
			if _, ok := complete[key]; !ok {
				keys = append(keys, key)
			}
		}
		sort.Strings(keys)
		for _, key := range keys {
			complete[key] = function(pending[key])
		}
	}
	var output bytes.Buffer
	output.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\npackage viewproto\n\nimport (\"frontlinecommand/pkg/content\";\"frontlinecommand/pkg/sim\"; pb \"frontlinecommand/protocol\")\n\n")
	keys := []string{}
	for key := range complete {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		output.WriteString(complete[key])
	}
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		panic(err)
	}
	if len(os.Args) > 1 && os.Args[1] == "-check" {
		old, err := os.ReadFile("snapshot_generated.go")
		if err != nil || !bytes.Equal(old, formatted) {
			panic("snapshot converter is stale; run go generate")
		}
		return
	}
	if err = os.WriteFile("snapshot_generated.go", formatted, 0644); err != nil {
		panic(err)
	}
	fmt.Printf("generated %d public message converters\n", len(complete))
}
